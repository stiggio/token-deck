const UNKNOWN: Glyph = g(5, ['11111', '10001', '10001', '10001', '10001', '10001', '11111'])

const NARROW2 = new Set(['.', ':', ',', "'"])
const NARROW3 = new Set(['/', '-', 'I', '1'])

export function glyphFor(ch: string): Glyph {
  return glyphs[ch] ?? UNKNOWN
}

export function glyphWidth(ch: string): number {
  if (ch === ' ') return 3
  if (NARROW2.has(ch)) return 2
  if (NARROW3.has(ch)) return 3
  return glyphFor(ch).w
}

export function advance(ch: string): number {
  if (ch === ' ') return 3
  return glyphWidth(ch) + 1
}

/** Ink width: sum of advances, with the last glyph contributing its width only. */
export function measure(text: string): number {
  if (!text) return 0
  let n = 0
  for (let i = 0; i < text.length; i++) {
    const ch = text[i]!
    n += i === text.length - 1 ? glyphWidth(ch) : advance(ch)
  }
  return n
}

export function fitText(text: string, maxWidth: number, maxChars = 64): string {
  let s = [...text].slice(0, maxChars).join('')
  while (s.length > 0 && (measure(s) > maxWidth || [...s].length > maxChars)) {
    s = [...s].slice(0, -1).join('')
  }
  return s
}

/** Keep a suffix, breaking at - _ or space when the whole string does not fit. */
export function fitTitle(text: string, maxWidth = 50): string {
  const u = text.toUpperCase()
  if (measure(u) <= maxWidth) return u
  const indexes = [0]
  for (let i = 0; i < u.length; i++) {
    if (u[i] === '-' || u[i] === '_' || u[i] === ' ') indexes.push(i + 1)
  }
  for (const i of indexes) {
    const tail = u.slice(i).trim()
    if (tail && measure(tail) <= maxWidth) return tail
  }
  let tail = u
  while (tail.length > 1 && measure(tail) > maxWidth) tail = tail.slice(1)
  return tail
}

export type Blit = { x: number; y: number; w: number; h: number }

export function glyphRects(ch: string, x: number, y: number): Blit[] {
  const glyph = glyphFor(ch)
  const rects: Blit[] = []
  const paint = (rows: string[], y0: number) => {
    rows.forEach((row, ry) => {
      for (let rx = 0; rx < row.length; rx++) {
        if (row[rx] === '1') rects.push({ x: x + rx, y: y0 + ry, w: 1, h: 1 })
      }
    })
  }
  paint(glyph.rows, y)
  if (glyph.desc) paint(glyph.desc, y + 7)
  return rects
}

export function textRects(text: string, x: number, y: number): Blit[] {
  const rects: Blit[] = []
  let pen = x
  for (const ch of text) {
    rects.push(...glyphRects(ch, pen, y))
    pen += advance(ch)
  }
  return rects
}
